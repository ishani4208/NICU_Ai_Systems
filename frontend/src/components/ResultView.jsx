import { useMemo } from "react";
import { marked } from "marked";
import DOMPurify from "dompurify";
import ClassificationBadge from "./ClassificationBadge.jsx";
import ProbabilityBars from "./ProbabilityBars.jsx";
import SpectrogramPlayer from "./SpectrogramPlayer.jsx";
import AnalysisProgress from "./AnalysisProgress.jsx";
import { ReportIcon } from "./Icons.jsx";

const LOW_CONFIDENCE = 0.8;

// Configure marked options for clean GFM table & list rendering
marked.setOptions({
  gfm: true,
  breaks: true,
});

// LLMs sometimes emit LaTeX such as $SpO_2$; show it as plain text (SpO2)
function stripInlineMath(text) {
  return text.replace(/\$([^$\s]{1,30})\$/g, (_, inner) =>
    inner.replace(/\\text\{([^}]*)\}/g, "$1").replace(/_\{?([A-Za-z0-9]+)\}?/g, "$1")
  );
}

function ReportSkeleton() {
  return (
    <div className="report-skeleton" aria-hidden="true">
      <div className="skeleton skeleton-line" style={{ width: "38%", height: 18 }} />
      <div className="skeleton skeleton-line" style={{ width: "92%" }} />
      <div className="skeleton skeleton-line" style={{ width: "86%" }} />
      <div className="skeleton skeleton-line" style={{ width: "64%" }} />
      <div className="skeleton skeleton-line" style={{ width: "30%", height: 18, marginTop: 22 }} />
      <div className="skeleton skeleton-line" style={{ width: "88%" }} />
      <div className="skeleton skeleton-line" style={{ width: "74%" }} />
    </div>
  );
}

export default function ResultView({ record }) {
  const status = record.reportStatus || "done";
  const htmlContent = useMemo(() => {
    if (!record?.report) return "";
    try {
      return DOMPurify.sanitize(marked.parse(stripInlineMath(record.report)));
    } catch {
      return DOMPurify.sanitize(record.report);
    }
  }, [record?.report]);

  const lowConfidence = record.confidence < LOW_CONFIDENCE;
  const pct = (record.confidence * 100).toFixed(1);

  return (
    <div className="grid-2">
      <div className="card reveal" style={{ "--i": 0 }}>
        <h3>Audio &amp; spectrogram</h3>
        <SpectrogramPlayer audioUrl={record.audioUrl} spectrogramUrl={record.spectrogramUrl} />
      </div>

      <div className="card classify-card reveal" style={{ "--i": 1 }} data-class={record.predictedClass}>
        <h3>Classification</h3>
        {lowConfidence && (
          <div className="alert alert-warning" role="alert">
            <strong>Low confidence ({pct}%).</strong> Verify manually by auscultation before relying on this
            result.
          </div>
        )}
        <ClassificationBadge predictedClass={record.predictedClass} confidence={record.confidence} animate />
        <h4 className="subheading">Class probabilities</h4>
        <ProbabilityBars probabilities={record.probabilities} />
        <p className="verify-note">
          The model can be wrong even at high confidence. Always verify by auscultation.
        </p>
      </div>

      <div className="card report-card-full reveal" style={{ "--i": 2 }}>
        <div className="report-card-header">
          <span className="report-header-icon">
            <ReportIcon size={20} />
          </span>
          <h3>Clinical decision-support report</h3>
        </div>

        {status === "pending" && (
          <>
            <AnalysisProgress step={3} />
            <ReportSkeleton />
          </>
        )}

        {status === "failed" && (
          <div className="error-box">
            The report could not be generated. The classification above is still valid. Delete this report and
            analyse the recording again to retry.
          </div>
        )}

        {status === "done" && (
          <>
            {record.reportSource && record.reportSource !== "template" && (
              <p className="caption">Generated by {record.reportSource}.</p>
            )}
            <div className="report-markdown-body" dangerouslySetInnerHTML={{ __html: htmlContent }} />
          </>
        )}

        {record.notes && (
          <div className="notes-container">
            <h4>Clinical notes</h4>
            <p>{record.notes}</p>
          </div>
        )}
      </div>
    </div>
  );
}
